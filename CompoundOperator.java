package first_package;

public class CompoundOperator {
	public static void main(String[] args) {
		//Operators
		//prefix increment
		//postfix increment
		//prefix decrement
		//postfix decrement
		double x= 1;
		x  ++;
		-- x;
		System.out.println(Math.pow(x++,x++));
		System.out.println(x );
	}

}
